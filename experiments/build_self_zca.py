"""Round-#6 :Self-whitening: — ZCA from the learner's OWN games (provenance-clean).

The conditioning fix (F2) without the contamination: the corpus is generated by the pure
random-init seed itself (rules + RNG only), so the whitening statistics pass :Provenance:
outright and are distribution-matched to early own-play rather than to a trained model's
play. Outputs models/zca_self.npz and the whitened seed lineage.

Preconditions: models/qlearn_clean_seed.pt (raw space), rsearch4. Failure mode: none silent —
asserts verify the whitening round-trip before saving.

Usage: python build_self_zca.py [games=800]
"""
import sys

import numpy as np
import torch
import chess

from chessdq.cem_loop import encode_features
from rsearch4 import play_games

GAMES = int(sys.argv[1]) if len(sys.argv) > 1 else 800


def main():
    ck = torch.load("models/qlearn_clean_seed.pt", map_location="cpu")
    assert not ck.get("zca"), "self-ZCA corpus seed must be RAW space"
    w = ck["state_dict"]["head.weight"].reshape(-1).double().numpy()
    b = float(ck["state_dict"]["head.bias"].reshape(-1)[0])

    print(f"corpus: {GAMES} OWN games (random-init seed, d1, tau 0.7 softmax)...", flush=True)
    games = play_games(list(w), b, list(w), b, 1, GAMES, 12, 1, 0.0, 160, 7, tau=0.7)
    X = np.stack([encode_features(chess.Board(f))
                  for _z, _aw, recs in games for f, _v, _p in recs]).astype(np.float64)
    print(f"positions: {X.shape[0]}", flush=True)
    mu = X.mean(axis=0)
    Xc = X - mu
    cov = (Xc.T @ Xc) / len(Xc)
    evals, evecs = np.linalg.eigh(cov + 1e-3 * np.eye(cov.shape[0]))
    Z = evecs @ np.diag(evals ** -0.5) @ evecs.T
    np.savez("models/zca_self.npz", Z=Z, mu=mu)

    wp = np.linalg.solve(Z, w)
    bp = b + float(w @ mu)
    x0 = encode_features(chess.Board()).astype(np.float64)
    raw = float(w @ x0) + b
    whitened = float(wp @ (Z @ (x0 - mu))) + bp
    assert abs(raw - whitened) < 1e-6, (raw, whitened)

    sd = {"head.weight": torch.tensor(wp, dtype=torch.float32).reshape(1, 809),
          "head.bias": torch.tensor([bp], dtype=torch.float32)}
    torch.save({"state_dict": sd, "arch": "linear", "enc": "kc", "zca": True, "cum_games": 0},
               "models/qlearn_self_seed.pt")
    print("models/zca_self.npz + models/qlearn_self_seed.pt — provenance: rules+RNG+own games, PASSES")


if __name__ == "__main__":
    main()
